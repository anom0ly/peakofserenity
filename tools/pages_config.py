#!/usr/bin/env python3
"""Write .pages.yml (the Pages CMS editor configuration) from src/guideTypes.json and blog/authors.yml.

Usage: python3 -I tools/pages_config.py [REPO_ROOT]
Run it after adding a guide type or an author, so every tab and author shows up in the editor.
Field types and keys checked against the Pages CMS docs (pagescms.org/docs, 2.x) on 2026-10-22.
"""
import json
import os
import sys

import yaml

HEADER = """\
# Pages CMS configuration (https://pagescms.org). Authors sign in by email invite; every Save commits to
# this repo and Cloudflare Pages rebuilds the site.
# GENERATED by tools/pages_config.py from src/guideTypes.json and blog/authors.yml: edit those (or the script)
# and re-run it rather than editing this file by hand.
"""

MD = {"format": "markdown"}
TALENT_NOTE = "Paste talent import strings exactly as they are."


def rich(name, label, description=None):
    f = {"name": name, "label": label, "type": "rich-text"}
    if description:
        f["description"] = description
    f["options"] = MD
    return f


def hidden(name, type_="string"):
    return {"name": name, "type": type_, "hidden": True}


def tab_group(group, label):
    fields = [
        {"name": "heading", "label": "Section heading", "type": "string",
         "description": "The title shown above these tabs."},
        rich("intro", "Text above the tabs", "Optional. Shown between the heading and the tabs."),
    ]
    for name, tab in group["tabs"]:
        fields.append(rich(name, "Tab: %s" % tab,
                           'Everything shown when a reader clicks the "%s" tab. %s' % (tab, TALENT_NOTE)))
    if group.get("wp_outro"):
        fields.append(rich("outro", "Text below the tabs", "Optional. Shown under the tabs."))
    return {"name": group["key"].split(".")[-1], "label": label, "type": "object", "fields": fields}


def guide_fields(gtype=None):
    fields = [
        {"name": "title", "label": "Guide title", "type": "string", "required": True},
        {"name": "last_update", "label": "Last updated", "type": "object",
         "description": "Change this date whenever you update the guide; it shows at the bottom of the page.",
         "fields": [{"name": "date", "label": "Date", "type": "date", "options": {"format": "yyyy-MM-dd"}}]},
        {"name": "authors", "label": "Authors", "component": "authors"},
        {"name": "description", "label": "Short summary", "type": "text",
         "description": "One or two sentences for Google and link previews."},
    ]
    if gtype:
        fields.append(rich("intro", "Introduction", "The text at the top of the guide, under the banner."))
        nested = {}
        for g in gtype["groups"]:
            parent, _, child = g["key"].rpartition(".")
            if not parent:
                fields.append(tab_group(g, g["heading"]))
                continue
            # Dotted keys (priority.singletarget) become an object of objects
            if parent not in nested:
                nested[parent] = {"name": parent, "label": g["heading"], "type": "object", "fields": []}
                fields.append(nested[parent])
            nested[parent]["fields"].append(tab_group(g, g.get("label", child)))
        fields.append(rich("body", "Rest of the guide", gtype["body"]))
    else:
        fields.append(rich("body", "Page"))
    fields += [{"name": "slug", "label": "Page address", "type": "string", "hidden": True}]
    if gtype:
        fields.append(hidden("guide_type"))
    fields += [hidden("wp_id", "number"), hidden("original_url")]
    return fields


def post_fields(podcast=False):
    fields = [
        {"name": "title", "label": "Title", "type": "string", "required": True},
        {"name": "date", "label": "Publish date", "type": "date", "required": True,
         "description": "When it goes up. Its web address uses the day you first create it.",
         "options": {"time": True, "format": "yyyy-MM-dd'T'HH:mm:ss"}},
        {"name": "authors", "label": "Author(s)", "component": "authors", "required": True,
         "description": "Pick yourself. Add co-authors if you wrote it together."},
        {"name": "tags", "label": "Tags", "type": "string", "list": True,
         "description": "Spec (Windwalker, Brewmaster, Mistweaver or General), patch number (e.g. 12.1), and any topics."},
    ]
    if podcast:
        fields += [
            {"name": "series", "label": "Show", "type": "string", "list": True,
             "description": "e.g. PeakCraft Podcast."},
            {"name": "audio", "label": "Audio file address", "type": "string",
             "description": "The full https:// address of the episode's MP3."},
            {"name": "duration", "label": "Length", "type": "string", "description": "e.g. 1:02:44"},
        ]
    fields += [
        {"name": "description", "label": "Short summary", "type": "text",
         "description": "One or two sentences shown on the list page, in Google and in Discord link previews."},
        {"name": "image", "label": "Preview image", "type": "image",
         "description": "Optional. Shown when it is shared."},
        rich("body", "Show notes" if podcast else "Post"),
        hidden("slug"), hidden("wp_id", "number"), hidden("original_url"),
    ]
    return fields


def dated_collection(name, label, path, podcast=False):
    c = {
        "name": name, "label": label, "type": "collection", "path": path,
        "filename": "{year}-{month}-{day}-{primary}.mdx", "format": "yaml-frontmatter",
        "view": {"fields": ["title", "date", "authors"], "primary": "title", "sort": ["date"],
                 "default": {"sort": "date", "order": "desc"}},
        "fields": post_fields(podcast),
    }
    if not podcast:
        c["exclude"] = ["authors.yml", "tags.yml"]
    c["operations"] = {"rename": False}  # renaming would change the post's address
    return c


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "."
    types = json.load(open(os.path.join(root, "src", "guideTypes.json")))
    authors = sorted(yaml.safe_load(open(os.path.join(root, "blog", "authors.yml"))))
    no_edit = {"create": False, "rename": False, "delete": False}

    guides = []
    for name, t in types.items():
        guides.append({"name": name, "label": t["title"], "type": "file", "path": t["file"],
                       "format": "yaml-frontmatter", "fields": guide_fields(t)})
    tabbed = [t["file"][len("docs/"):] for t in types.values()]
    guides.append({
        "name": "pages", "label": "Other guide pages", "type": "collection", "path": "docs",
        # Tells Pages CMS to list .mdx files; without it, only .md files show up.
        "filename": "{primary}.mdx", "subfolders": True, "format": "yaml-frontmatter",
        # The tabbed guides have their own entries above. Every tabbed guide file is named pve-guide.mdx,
        # so this works whether exclude matches file names or paths.
        "exclude": sorted(set(["pve-guide.mdx"] + tabbed)),
        "view": {"fields": ["title", "last_update"], "primary": "title"},
        "fields": guide_fields(), "operations": no_edit,
    })
    config = {
        "media": {"input": "static/img", "output": "/img"},
        "components": {"authors": {"label": "Authors", "type": "select",
                                   "options": {"values": authors, "multiple": True}}},
        "content": [
            dated_collection("news", "News Posts", "blog"),
            {"name": "guides", "label": "Guides", "type": "group", "items": guides},
            dated_collection("podcast", "Podcast Episodes", "podcast", podcast=True),
            {"name": "authors", "label": "Authors", "type": "file", "path": "blog/authors.yml", "format": "code"},
        ],
    }
    with open(os.path.join(root, ".pages.yml"), "w") as f:
        f.write(HEADER)
        yaml.dump(config, f, sort_keys=False, allow_unicode=True, width=120)
    print("wrote .pages.yml: %d tabbed guides, %d authors" % (len(types), len(authors)))


if __name__ == "__main__":
    main()
